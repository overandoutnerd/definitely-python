feedback = input("Feedback: ")
search = input("Word to search: ")
repl = input("Replacement: ")
words = feedback.split()

print("\n========================================")
print(" UNIVERSITY FEEDBACK DASHBOARD")
print("========================================")
print("Characters:", len(feedback))
print("Words:", len(words))
print("Uppercase:", feedback.upper())
print("Lowercase:", feedback.lower())
print("First Word:", words[0] if words else "")
print("Last Word:", words[-1] if words else "")
print("Search Count:", feedback.lower().count(search.lower()))
print("Updated:", feedback.replace(search, repl))
print("========================================")